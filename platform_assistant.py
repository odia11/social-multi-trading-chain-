def _prepare_reasoning(d, source_id, wallet, kind, now):
    """Do optional external reasoning before the write transaction.

    Only a sanitized public feed question and reviewed facts leave the process.
    No account/private tables are read into the model prompt.
    """
    with sqlite3.connect(d.DB_FILE, timeout=2) as c:
        if not enabled(c, 'replies'):
            return None
        author = identity(c)
        if not author:
            return None
        context_topic = None
        action_state = None
        if kind == 'post':
            row = c.execute(
                'SELECT p.content,u.id FROM feed_posts p JOIN users u ON u.wallet_address=p.wallet '
                'WHERE p.id=? AND p.wallet=?',
                (source_id,wallet),
            ).fetchone()
            if not row or row[1] == author[0]:
                return None
            text = d._feed_text_part(row[0]) if hasattr(d,'_feed_text_part') else re.split(
                r'__(?:CHART|TRADE|CALL)__',row[0],maxsplit=1
            )[0]
        else:
            source = c.execute(
                'SELECT user_id,post_id,message,created_at,parent_reply_id FROM feed_replies WHERE id=?',
                (source_id,),
            ).fetchone()
            if not source or source[0] == author[0] or source[1][:1] not in ('p','t'):
                return None
            member = c.execute('SELECT wallet_address FROM users WHERE id=?',(source[0],)).fetchone()
            if not member or member[0] != wallet:
                return None
            text = _conversation_message(c,d,source,author[0],now)
            previous = learning.prior(c,d,source,author[0])
            context_topic = previous[0] if previous else None
            action_state = _trade_thread_state(c,d,source,author[0]) if context_topic == 'trade_action' else None
        if not MENTION.search(text):
            return None
        raw = MENTION.sub('',text).strip()
        # Never send live-data questions to the reasoning provider. Their
        # deterministic data modules are authoritative and privacy-scoped.
        if prices.query(raw) or public_data.query(raw):
            return None
        deterministic = answer(text, context_topic, action_state=action_state)
    smart = reasoner.reason(d, raw, context_topic, deterministic)
    return (text, smart) if smart else None


def _reasoning_for(text, prepared):
    return prepared[1] if prepared and prepared[0] == text else None

def _chat_source(d, source_id, wallet, kind, now):
    """Public inputs for a conversational (Grok-style) reply, or None when a
    deterministic module owns the answer. No network; reads only public
    Home-feed text and usernames (orcagent_chat.thread_context)."""
    with sqlite3.connect(d.DB_FILE, timeout=2) as c:
        if not enabled(c, 'replies'):
            return None
        author = identity(c)
        if not author:
            return None
        context_topic = None
        action_state = None
        thread = []
        if kind == 'post':
            row = c.execute(
                'SELECT p.content,u.id,u.username FROM feed_posts p JOIN users u ON u.wallet_address=p.wallet '
                'WHERE p.id=? AND p.wallet=?',
                (source_id, wallet),
            ).fetchone()
            if not row or row[1] == author[0]:
                return None
            text = d._feed_text_part(row[0]) if hasattr(d, '_feed_text_part') else re.split(
                r'__(?:CHART|TRADE|CALL)__', row[0], maxsplit=1)[0]
            user_id, asker = row[1], row[2]
        else:
            source = c.execute(
                'SELECT user_id,post_id,message,created_at,parent_reply_id FROM feed_replies WHERE id=?',
                (source_id,),
            ).fetchone()
            if not source or source[0] == author[0] or source[1][:1] not in ('p', 't'):
                return None
            member = c.execute('SELECT wallet_address,username FROM users WHERE id=?', (source[0],)).fetchone()
            if not member or member[0] != wallet:
                return None
            text = _conversation_message(c, d, source, author[0], now)
            previous = learning.prior(c, d, source, author[0])
            context_topic = previous[0] if previous else None
            action_state = _trade_thread_state(c, d, source, author[0]) if context_topic == 'trade_action' else None
            user_id, asker = source[0], member[1]
            thread = chat.thread_context(c, d, source[1], source[4], author[0])
        if not MENTION.search(text):
            return None
        raw = MENTION.sub('', text).strip()
        # Live data, own-account privacy, actions and secrets stay deterministic.
        if not raw or chat.private_request(raw) or prices.query(raw) or public_data.query(raw):
            return None
        deterministic = answer(text, context_topic, action_state=action_state)
        if deterministic and deterministic[0] in chat.DETERMINISTIC_TOPICS:
            return None
    facts = deterministic[1] if deterministic and deterministic[0] not in ('scope', 'welcome', 'overview') else None
    return {'text': text, 'raw': raw, 'asker': asker, 'user_id': user_id, 'thread': thread, 'facts': facts}


def wants_chat(d, source_id, wallet, kind, now=None):
    if not chat.available(d):
        return False
    try:
        return _chat_source(d, source_id, wallet, kind, time.time() if now is None else now) is not None
    except Exception:
        return False


def chat_then_reply(d, source_id, wallet, kind):
    """Background: ask the model, then publish (falls back to the
    deterministic answer when the model gives nothing usable)."""
    try:
        now = time.time()
        src = _chat_source(d, source_id, wallet, kind, now)
        result = None
        if src:
            got = chat.reply(d, src['raw'], src['asker'], src['thread'], src['user_id'], src['facts'], now)
            result = (src['text'], got) if got else None
        if kind == 'post':
            reply_to_post(d, source_id, wallet, chat_answer=result)
        else:
            reply_to(d, source_id, wallet, chat_answer=result)
    except Exception:
        try:
            d.app.logger.exception('orcagent chat reply failed')
        except Exception:
            pass


def member_name(c, user_id):
    row = c.execute('SELECT username FROM users WHERE id=?', (user_id,)).fetchone()
    return row[0] if row and row[0] else 'user'


def _local_brain(text, asker, thread, response):
    """OrcAgent's own conversational answer (orcagent_brain) when no model
    answered: never for live data, actions, secrets or privacy, which their
    deterministic modules own."""
    # Only for a message addressed to OrcAgent (a tag, or a reply in a
    # conversation with it, which _conversation_message prefixes): the
    # deterministic layer answered None for everything else.
    if not isinstance(text, str) or not response or not MENTION.search(text):
        return response
    if response[0] in chat.DETERMINISTIC_TOPICS:
        return response
    raw = MENTION.sub('', text).strip()
    if not raw or chat.private_request(raw) or prices.query(raw) or public_data.query(raw):
        return response
    try:
        local = brain.reply(chat.redact(raw, chat.MAX_QUESTION), asker, thread, response)
    except Exception:
        local = None
    if local:
        clean = chat.safe_output(local[1])
        if clean:
            return (local[0], clean)
    return response


def _privacy_guard(text, response):
    """Absolute: a question about anyone's private account matters is always
    answered with the refusal, whatever any other layer produced."""
    if isinstance(text, str) and chat.private_request(MENTION.sub('', text)):
        return ('privacy', chat.PRIVACY_REFUSAL)
    return response


def reply_to_post(d,post_number,wallet,now=None,chat_answer=None):
    # Only a successfully authenticated NEW post; no edits, reposts or backfill.
    if type(post_number) is not int or post_number<=0:
        return None
    now = time.time() if now is None else now
    market = _prepare_market(d,post_number,wallet,'post',now)
    public = _prepare_public(d,post_number,wallet,'post',now)
    # While the conversational layer is on it owns every model call (with its
    # privacy guard); the older reasoning fallback only runs when it is off.
    reasoning = None if (chat_answer or chat.available(d)) else _prepare_reasoning(d,post_number,wallet,'post',now)
    with sqlite3.connect(d.DB_FILE,timeout=8) as c:
        c.execute('BEGIN IMMEDIATE')
        if not enabled(c,'replies'):
            return None
        author = identity(c)
        if not author:
            return None
        post = c.execute('SELECT wallet,content FROM feed_posts WHERE id=?',(post_number,)).fetchone()
        member = c.execute('SELECT id FROM users WHERE wallet_address=?',(wallet,)).fetchone()
        if not post or post[0]!=wallet or not member or member[0]==author[0]:
            return None
        text = d._feed_text_part(post[1]) if hasattr(d,'_feed_text_part') else re.split(r'__(?:CHART|TRADE|CALL)__',post[1],maxsplit=1)[0]
        response = answer(text,market=_market_for(text,market),public=_public_for(text,public))
        smart = _reasoning_for(text,reasoning)
        if smart and response and smart[0] == response[0]:
            response = smart
        talk = _reasoning_for(text,chat_answer)
        if talk and (not response or response[0] not in chat.DETERMINISTIC_TOPICS):
            response = talk
        elif not talk:
            response = _local_brain(text, member_name(c, member[0]), [], response)
        response = _privacy_guard(text, response)
        key = 'post-reply:'+str(post_number)
        if not response or c.execute('SELECT 1 FROM platform_assistant_events WHERE event_key=?',(key,)).fetchone() or not within_reply_limits(c,member[0],now):
            return None
        topic,message = response
        if enabled(c,'learning'):
            learning.record_contact(
                c,'post',str(post_number),member[0],text,topic,topic,None,MENTION,now
            )
        post_id = 'p'+str(post_number)
        cur = c.execute('INSERT INTO feed_replies(user_id,post_id,message,created_at,parent_reply_id) VALUES(?,?,?,?,NULL)',
                        (author[0],post_id,message,utcstamp(now)))
        c.execute('INSERT INTO platform_assistant_events VALUES(?,?,?,?,?,?,?)',
                  (key,'reply',member[0],post_id,cur.lastrowid,topic,now))
        c.execute('INSERT INTO notifications(user_id,type,content,link,actor_wallet) VALUES(?,?,?,?,?)',
                  (member[0],'reply','OrcAgent replied to you',d._reply_link(c,post_id,cur.lastrowid),author[1]))
        return cur.lastrowid

def reply_to(d, source_id, wallet, now=None, chat_answer=None):
    now = time.time() if now is None else now
    market = _prepare_market(d,source_id,wallet,'reply',now)
    public = _prepare_public(d,source_id,wallet,'reply',now)
    # While the conversational layer is on it owns every model call (with its
    # privacy guard); the older reasoning fallback only runs when it is off.
    reasoning = None if (chat_answer or chat.available(d)) else _prepare_reasoning(d,source_id,wallet,'reply',now)
    with sqlite3.connect(d.DB_FILE, timeout=8) as c:
        c.execute('BEGIN IMMEDIATE')
        if not enabled(c, 'replies'):
            return None
        author = identity(c)
        if not author:
            return None
        source = c.execute('SELECT user_id,post_id,message,created_at,parent_reply_id FROM feed_replies WHERE id=?', (source_id,)).fetchone()
        if not source or source[0] == author[0]:
            return None
        member = c.execute('SELECT wallet_address FROM users WHERE id=?', (source[0],)).fetchone()
        if not member or member[0] != wallet or source[1][:1] not in ('p','t'):
            return None  # Home feed only; never publish private group context.
        created = d._feed_post_created_at(c, source[1])
        if not created or c.execute('SELECT datetime(?)>=datetime(?)', (source[3],created)).fetchone()[0] != 1:
            return None
        use_learning = enabled(c,'learning')
        previous = learning.prior(c,d,source,author[0]) if use_learning else None
        message = _conversation_message(c,d,source,author[0],now)
        action_state = _trade_thread_state(c,d,source,author[0]) if previous and previous[0] == 'trade_action' else None
        explicit = answer(message, previous[0] if previous else None, market=_market_for(message,market), public=_public_for(message,public), action_state=action_state)
        response = explicit
        if explicit and use_learning:
            if explicit[0]=='scope':
                topic = learning.lookup(c,d,source[2],MENTION,LEARNABLE,now)
                clean = MENTION.sub('',source[2])
                if not topic and previous and previous[0] in LEARNABLE and len(clean)<=160 and re.fullmatch(r'\s*(?:how|where|what next|hoe|waar)[\s?!.]*', clean, re.I) and not learning.UNSAFE.search(clean):
                    topic = previous[0]
                if topic:
                    response = topic, LABEL + LEARNABLE[topic]
        smart = _reasoning_for(message,reasoning)
        # Reviewed learned mappings outrank model wording. Otherwise a
        # reasoned answer may refine only the same deterministic intent.
        if smart and response is explicit and explicit and smart[0] == explicit[0]:
            response = smart
        # A conversational answer for anything a deterministic module does
        # not own (live data, actions, secrets, privacy).
        talk = _reasoning_for(message,chat_answer)
        if talk and (not explicit or explicit[0] not in chat.DETERMINISTIC_TOPICS):
            response = talk
        elif not talk:
            response = _local_brain(message, member_name(c, source[0]),
                                    chat.thread_context(c, d, source[1], source[4], author[0]), response)
        response = _privacy_guard(message, response)
        key = 'reply:' + str(source_id)
        if not response or c.execute('SELECT 1 FROM platform_assistant_events WHERE event_key=?', (key,)).fetchone():
            return None
        if not within_reply_limits(c,source[0],now):
            return None
        if use_learning:
            detected = explicit[0] if explicit else None
            learning.record_contact(
                c,'reply',str(source_id),source[0],source[2],detected,response[0],
                previous[0] if previous else None,MENTION,now
            )
            observed = explicit[0] if explicit[0]!='scope' or response[0]=='scope' else None
            learning.observe(c,d,source_id,source,observed,previous,MENTION,LEARNABLE,now)
        topic, message = response
        cur = c.execute('INSERT INTO feed_replies(user_id,post_id,message,created_at,parent_reply_id) VALUES(?,?,?,?,?)',
                        (author[0],source[1],message,utcstamp(now),source_id))
        c.execute('INSERT INTO platform_assistant_events VALUES(?,?,?,?,?,?,?)',
                  (key,'reply',source[0],source[1],cur.lastrowid,topic,now))
        c.execute('INSERT INTO notifications(user_id,type,content,link,actor_wallet) VALUES(?,?,?,?,?)',
                  (source[0],'reply','OrcAgent replied to you',d._reply_link(c,source[1],cur.lastrowid),author[1]))
        return cur.lastrowid

