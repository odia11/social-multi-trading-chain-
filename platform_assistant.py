def _clean_existing_prefixes(c):
    """Remove only fixed intros from recorded posts/replies of the verified agent."""
    if not c.in_transaction:
        c.execute('BEGIN IMMEDIATE')
    key = 'content_prefix_cleanup_v1'
    if c.execute('SELECT 1 FROM platform_assistant_settings WHERE key=?', (key,)).fetchone():
        return
    author = identity(c)
    if not author:
        return
    prefix = 'OrcAgent · Platform thesis (automated)'
    posts = c.execute("SELECT p.id,p.content FROM feed_posts p JOIN platform_assistant_events e "
                      "ON e.post_id='p'||p.id AND e.kind='post' WHERE p.wallet=?", (author[1],)).fetchall()
    for post_id, content in posts:
        if isinstance(content, str) and content.startswith(prefix):
            c.execute('UPDATE feed_posts SET content=? WHERE id=? AND content=?',
                      (content[len(prefix):].lstrip(), post_id, content))
    prefix = 'Automated · '
    replies = c.execute("SELECT r.id,r.message FROM feed_replies r JOIN platform_assistant_events e "
                        "ON e.reply_id=r.id AND e.kind='reply' WHERE r.user_id=?", (author[0],)).fetchall()
    for reply_id, message in replies:
        if isinstance(message, str) and message.startswith(prefix):
            c.execute('UPDATE feed_replies SET message=? WHERE id=? AND message=?',
                      (message[len(prefix):].lstrip(), reply_id, message))
    c.execute('INSERT OR IGNORE INTO platform_assistant_settings VALUES(?,?)', (key, '1'))


def _remove_retired_posts(c):
    """Once: delete the posts OrcAgent itself published with a RETIRED text,
    with their replies, likes, reposts and notifications. Only posts recorded
    as published by this assistant, from the official account, are touched."""
    key = 'retired_posts_cleanup_v1'
    if c.execute('SELECT 1 FROM platform_assistant_settings WHERE key=?', (key,)).fetchone():
        return 0
    author = identity(c)
    if not author:
        return 0   # no official account yet; try again next start
    marks = ','.join('?' * len(RETIRED))
    ids = [r[0] for r in c.execute(
        "SELECT p.id FROM feed_posts p JOIN platform_assistant_events e ON e.post_id='p'||p.id AND e.kind='post' "
        "WHERE p.wallet=? AND p.content IN (%s)" % marks, (author[1],) + tuple(RETIRED))]
    for post_id in ids:
        pid, link = 'p%d' % post_id, '/#post-p%d' % post_id
        for sql, args in (
                ('DELETE FROM feed_reply_likes WHERE reply_id IN (SELECT id FROM feed_replies WHERE post_id=?)', (pid,)),
                ('DELETE FROM feed_replies WHERE post_id=?', (pid,)),
                ('DELETE FROM post_likes WHERE post_id=?', (pid,)),
                ('DELETE FROM post_reactions WHERE post_id=?', (pid,)),
                ('DELETE FROM feed_reposts WHERE post_id=?', (pid,)),
                ('DELETE FROM notifications WHERE link=? OR link LIKE ?', (link, link + '-reply-%'))):
            try:
                c.execute(sql, args)
            except sqlite3.OperationalError:
                pass   # a table this database does not have
        c.execute('DELETE FROM feed_posts WHERE id=?', (post_id,))
    c.execute('INSERT OR IGNORE INTO platform_assistant_settings VALUES(?,?)', (key, str(len(ids))))
    if ids:
        print('[platform-assistant] removed %d earlier post(s) with an untrue product text' % len(ids), flush=True)
    return len(ids)


def enabled(c, key):
    env = {'posts':'ORCAGENT_PLATFORM_POSTS','replies':'ORCAGENT_PLATFORM_REPLIES','learning':'ORCAGENT_PLATFORM_LEARNING'}[key]
    if os.environ.get(env, '1') == '0':
        return False
    row = c.execute('SELECT value FROM platform_assistant_settings WHERE key=?', (key,)).fetchone()
    return not row or row[0] == '1'

def identity(c):
    pinned = c.execute("SELECT value FROM platform_assistant_settings WHERE key='author_id'").fetchone()
    rows = c.execute("SELECT id,wallet_address,username FROM users WHERE lower(username)='orcagent' AND is_verified=1").fetchall()
    if len(rows) != 1 or (pinned and str(rows[0][0]) != pinned[0]):
        return None
    if not pinned:
        c.execute("INSERT INTO platform_assistant_settings VALUES('author_id',?)", (str(rows[0][0]),))
    return rows[0]

def utcstamp(now):
    return dt.datetime.fromtimestamp(now, dt.timezone.utc).strftime('%Y-%m-%d %H:%M:%S')

def due_slot(now):
    local = dt.datetime.fromtimestamp(now, TZ)
    slot = local.replace(minute=local.minute - local.minute % SLOT_MINUTES, second=0, microsecond=0)
    if 0 <= now - slot.timestamp() < SLOT_WINDOW:
        return slot
    return None

def slot_index(slot):
    """Position of this slot within its day: 0 at 00:00 ... 47 at 23:30."""
    return (slot.hour * 60 + slot.minute) // SLOT_MINUTES

def _opening(text):
    """The first three words: how a post opens."""
    return ' '.join(str(text or '').split()[:3]).lower()

def publish_due(db, now=None, live_data=None, render=None):
    """Publish this slot's post, if it is due and not yet published.

    live_data(), when given, returns (trending tokens, SOL price in USD). The
    post is then the best current live post about calls or trending tokens
    (platform_live_posts); render(picture spec, seed), when given, draws its
    picture (agent_post_images) and returns the image URL. Both happen before
    the write transaction, so slow logo or price sources never hold the
    database lock. A post whose picture could not be drawn carries the live
    call or chart card instead. Only when nothing is live does a product text
    go out. OrcAgent never posts a text it has posted before: if every option
    was already used, the slot is skipped.
    """
    now = time.time() if now is None else now
    slot = due_slot(now)
    if slot is None:
        return None  # Skip missed slots; never flood the feed after downtime.
    key = 'post:' + slot.isoformat()

    def fresh(c, wallet, text):
        return not c.execute('SELECT 1 FROM feed_posts WHERE wallet=? AND content=?', (wallet, text)).fetchone()

    picked = None   # (topic, content, image_url)
    if live_data is not None:
        with sqlite3.connect(db, timeout=8) as c:
            if c.execute('SELECT 1 FROM platform_assistant_events WHERE event_key=?', (key,)).fetchone():
                return None
            if not enabled(c, 'posts'):
                return None
            author = identity(c)
            if not author:
                return None
        try:
            tokens, sol_usd = live_data()
        except Exception:
            tokens, sol_usd = [], 0.0
        choice = None
        with sqlite3.connect(db, timeout=8) as c:
            last = c.execute('SELECT content FROM feed_posts WHERE wallet=? ORDER BY id DESC LIMIT 1',
                             (author[1],)).fetchone()
            opening = _opening(last[0]) if last else ''
            for topic, texts, media, embed in live_posts.candidates(c, now, slot_index(slot), tokens, sol_usd):
                usable = [t for t in texts if fresh(c, author[1], t) and fresh(c, author[1], t + embed)]
                # Never open the way the previous post did.
                text = next((t for t in usable if _opening(t) != opening), None) or (usable[0] if usable else None)
                if text:
                    choice = (topic, text, media, embed)
                    break
            variant = 0
            if choice and choice[2]:
                prefixes = ('trending:',) if choice[2]['kind'] == 'trending' else ('call:', 'milestone:', 'best:')
                variant = sum(c.execute("SELECT COUNT(*) FROM platform_assistant_events WHERE kind='post' AND topic LIKE ?",
                                        (p_ + '%',)).fetchone()[0] for p_ in prefixes)
        if choice:
            topic, text, media, embed = choice
            image_url = None
            if media and render is not None:
                try:
                    image_url = render(media, topic + '|' + slot.isoformat(), variant)
                except Exception:
                    image_url = None
            picked = (topic, text if image_url else text + embed, image_url)

    with sqlite3.connect(db, timeout=8) as c:
        c.execute('BEGIN IMMEDIATE')
        if not enabled(c, 'posts'):
            return None
        author = identity(c)
        if not author:
            return None
        if c.execute('SELECT 1 FROM platform_assistant_events WHERE event_key=?', (key,)).fetchone():
            return None
        if picked is not None and not fresh(c, author[1], picked[1]):
            picked = None
        if picked is None:
            # A product text, in the daily rotation order, that OrcAgent has
            # never posted before.
            sequence = (slot.date() - dt.date(2026,10,4)).days * (24 * 60 // SLOT_MINUTES) + slot_index(slot)
            for i in range(len(THESES)):
                topic, text = THESES[(sequence + i) % len(THESES)]
                if fresh(c, author[1], text):
                    picked = (topic, text, None)
                    break
        if picked is None:
            return None
        topic, content, image_url = picked
        if image_url:
            cur = c.execute('INSERT INTO feed_posts(wallet,content,created_at,image_url) VALUES(?,?,?,?)',
                            (author[1], content, utcstamp(now), image_url))
        else:
            cur = c.execute('INSERT INTO feed_posts(wallet,content,created_at) VALUES(?,?,?)',
                            (author[1], content, utcstamp(now)))
        post_id = 'p'+str(cur.lastrowid)
        c.execute('INSERT INTO platform_assistant_events VALUES(?,?,?,?,?,?,?)',
                  (key,'post',None,post_id,None,topic,now))
        return post_id

